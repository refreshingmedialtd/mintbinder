import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourceUrl = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv";
const outputUrl = new URL("../src/lib/catalogue/pokemon-name-aliases.generated.ts", import.meta.url);
const supportedLanguageIds = new Set([1, 2, 3, 4, 11, 12]);
const englishLanguageId = 9;

const response = await fetch(sourceUrl, { headers: { accept: "text/csv" } });

if (!response.ok) {
  throw new Error(`Pokemon name source failed with HTTP ${response.status}.`);
}

const rows = (await response.text()).trim().split(/\r?\n/).slice(1);
const namesBySpecies = new Map();

for (const row of rows) {
  const [speciesIdValue, languageIdValue, name] = row.split(",", 3);
  const speciesId = Number(speciesIdValue);
  const languageId = Number(languageIdValue);

  if (!speciesId || !name || (languageId !== englishLanguageId && !supportedLanguageIds.has(languageId))) {
    continue;
  }

  const species = namesBySpecies.get(speciesId) ?? { aliases: new Set(), english: "" };

  if (languageId === englishLanguageId) {
    species.english = name;
  } else {
    species.aliases.add(name);
  }

  namesBySpecies.set(speciesId, species);
}

const aliases = [...namesBySpecies.values()]
  .filter((species) => species.english)
  .flatMap((species) => [...species.aliases].map((alias) => [alias, species.english]))
  .filter(([alias, english]) => alias !== english)
  .sort((left, right) => right[0].length - left[0].length || left[0].localeCompare(right[0]));

const output = `// Generated by scripts/generate-pokemon-name-aliases.mjs from PokeAPI's multilingual species data.\n` +
  `// Source: ${sourceUrl}\n` +
  `export const GENERATED_POKEMON_NAME_ALIASES: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(aliases, null, 2)};\n`;

await writeFile(outputUrl, output, "utf8");
console.log(JSON.stringify({ aliases: aliases.length, output: fileURLToPath(outputUrl) }));
